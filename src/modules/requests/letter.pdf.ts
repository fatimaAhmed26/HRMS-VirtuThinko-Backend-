import { INK, MUTED, drawLetterhead, pdfToBuffer } from '../../utils/pdf';
import type { CompanyInfo } from '../../utils/settings';

export interface LetterData {
  company: CompanyInfo;
  title: string;
  reference: string;
  date: string;
  addressedTo: string;
  body: string;
  signatoryName: string;
  signatoryTitle: string;
}

export function renderLetterPdf(d: LetterData) {
  return pdfToBuffer((doc) => {
    const left = 50;
    const width = doc.page.width - 100;
    let y = drawLetterhead(doc, d.company, d.title, d.date);

    doc.font('Helvetica').fontSize(9).fillColor(MUTED).text(`Ref: ${d.reference}`, left, y);
    y += 24;
    doc.font('Helvetica-Bold').fontSize(11).fillColor(INK).text(`To: ${d.addressedTo}`, left, y);
    y = doc.y + 18;
    doc.font('Helvetica-Bold').fontSize(13).text(d.title, left, y, { width, align: 'center', underline: true });
    y = doc.y + 18;

    doc.font('Helvetica').fontSize(11).fillColor(INK);
    for (const para of d.body.split(/\n{2,}/)) {
      doc.text(para.trim(), left, y, { width, align: 'justify', lineGap: 3 });
      y = doc.y + 12;
    }

    y += 20;
    doc.text('Sincerely,', left, y);
    y = doc.y + 40;
    doc.font('Helvetica-Bold').text(d.signatoryName, left, y);
    if (d.signatoryTitle) doc.font('Helvetica').text(d.signatoryTitle, left, doc.y + 2);
    doc.font('Helvetica').text(d.company.name, left, doc.y + 2);

    doc.font('Helvetica').fontSize(8).fillColor(MUTED).text(
      `This letter was generated by the ${d.company.name} HR system (reference ${d.reference}). To verify it, please contact the HR department.`,
      left, doc.page.height - 80, { width, align: 'center' }
    );
  }, { info: { Title: `${d.title} ${d.reference}` } });
}